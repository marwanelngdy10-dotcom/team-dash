-- ------------------------------------------------------------
-- 1) عمود "آخر ظهور" — بيتحدّث من الواجهة كل 45 ثانية طول ما المستخدم
--    فاتح الموقع (heartbeat)، وكل عضو يقدر يحدّث صف نفسه بس (نفس صلاحية
--    users_update الموجودة أصلًا، مفيش حاجة إضافية مطلوبة هنا)
-- ------------------------------------------------------------

alter table public.users add column if not exists "lastSeenAt" timestamptz;

-- ------------------------------------------------------------
-- 2) تصحيح صلاحية "users_select": قبل كده العضو العادي كان يقدر يشوف
--    صف نفسه بس (مش زمايله)، فكانت صفحة "الشات" — من ناحية العضو
--    العادي — مش قادرة تعرض قائمة الأعضاء أصلًا عشان يختار يبعتلهم،
--    ولا حتى تعرف اسم مين بعتله رسالة خاصة. دلوقتي أي عضو نشط يقدر
--    يشوف باقي الأعضاء "النشطين" (id/name/avatar/role/status)
--    — الخصوصية الفعلية للرسائل الخاصة نفسها لسه محفوظة بالكامل عبر
--    RLS في جدول messages (v4)، اللي محدّش يشوفها غير طرفيها.
-- ------------------------------------------------------------

drop policy if exists "users_select" on public.users;
create policy "users_select" on public.users
  for select using (
    "authId" = auth.uid()
    or public.is_admin()
    or status = 'active'
  );

